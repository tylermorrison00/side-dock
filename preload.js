const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('sideDock', {
  getState: () => ipcRenderer.invoke('get-state'),
  setMode: (mode) => ipcRenderer.invoke('set-mode', mode),
  setPanel: (open) => ipcRenderer.invoke('set-panel', open),
  setHidden: (hidden) => ipcRenderer.invoke('set-hidden', hidden),
  setAutohide: (on) => ipcRenderer.invoke('set-autohide', on),
  showFromArrow: () => ipcRenderer.invoke('show-from-arrow'),
  onAutoHideShow: (cb) => ipcRenderer.on('auto-hide-show', cb),
  onAutoHideHide: (cb) => ipcRenderer.on('auto-hide-hide', cb),
  onAutoHideArrowOnly: (cb) => ipcRenderer.on('auto-hide-arrow-only', cb),
  setTheme: (theme) => ipcRenderer.invoke('set-theme', theme),
  setAutostart: (on) => ipcRenderer.invoke('set-autostart', on),
  doUpdate: () => ipcRenderer.invoke('do-update'),
  setGithubToken: (token) => ipcRenderer.invoke('set-github-token', token),
  clearGithubToken: () => ipcRenderer.invoke('clear-github-token'),
  addTool: (tool) => ipcRenderer.invoke('add-tool', tool),
  removeTool: (id) => ipcRenderer.invoke('remove-tool', id),
  launchTool: (tool) => ipcRenderer.invoke('launch-tool', tool),
  minimize: () => ipcRenderer.invoke('window-min'),
  close: () => ipcRenderer.invoke('window-close'),
  setMouseEvents: (ignore) => ipcRenderer.invoke('set-mouse-events', ignore),
  getTodos: () => ipcRenderer.invoke('get-todos'),
  addTodo: (text) => ipcRenderer.invoke('add-todo', text),
  toggleTodo: (id) => ipcRenderer.invoke('toggle-todo', id),
  deleteTodo: (id) => ipcRenderer.invoke('delete-todo', id),
  editTodo: (id, text) => ipcRenderer.invoke('edit-todo', id, text),
  getNotes: () => ipcRenderer.invoke('get-notes'),
  addNote: (data) => ipcRenderer.invoke('add-note', data),
  copyNote: (text) => ipcRenderer.invoke('copy-note', text),
  deleteNote: (id) => ipcRenderer.invoke('delete-note', id),
  restoreNote: (item) => ipcRenderer.invoke('restore-note', item),
  restoreTodo: (item) => ipcRenderer.invoke('restore-todo', item),
  getHabits: () => ipcRenderer.invoke('get-habits'),
  addHabit: (name) => ipcRenderer.invoke('add-habit', name),
  deleteHabit: (id) => ipcRenderer.invoke('delete-habit', id),
  toggleHabit: (id) => ipcRenderer.invoke('toggle-habit', id),
  editHabit: (id, name) => ipcRenderer.invoke('edit-habit', id, name),
  restoreHabit: (item) => ipcRenderer.invoke('restore-habit', item),
  getBrightness: () => ipcRenderer.invoke('get-brightness'),
  setBrightness: (level) => ipcRenderer.invoke('set-brightness', level),
  getExtraDim: () => ipcRenderer.invoke('get-extra-dim'),
  setExtraDim: (level) => ipcRenderer.invoke('set-extra-dim', level),
  editNote: (id, data) => ipcRenderer.invoke('edit-note', id, data)
});
